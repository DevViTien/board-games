/** Every layout as written, for the layouts' tests. */
export const JELLY_CREW_LAYOUT_DEFINITIONS: readonly JellyCrewLayoutDefinition[] = [
  ...KITCHEN,
  ...DESSERT_SHOP,
  ...MARKET,
  ...COCONUT_GROVE,
  ...COLD_STORE,
  ...FLOATING_MARKET,
  ...JELLY_FACTORY,
  ...MOON_FESTIVAL,
];

const LAYOUTS = new Map(
  JELLY_CREW_LAYOUT_DEFINITIONS.map((definition) => [
    `${definition.map}-${String(definition.playerCount)}`,
    parseJellyCrewLayout(definition),
  ]),
);

/** The layout of `map` for `playerCount` players (2 to 4). */
export function jellyCrewLayout(map: JellyCrewMapId, playerCount: number): JellyCrewLayout {
  const layout = LAYOUTS.get(`${map}-${String(playerCount)}`);
  if (layout === undefined) throw new Error(`No layout ${map} for ${String(playerCount)} players`);
  return layout;
}
